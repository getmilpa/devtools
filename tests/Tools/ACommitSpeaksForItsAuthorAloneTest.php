    public function testACommitWithACoauthorTrailerIsRefusedAndNeverQuoted(): void
    {
        [$code, $said] = $this->gate($this->pullRequestEvent(7), self::api(7, 'fix: x', 'A body.', ['fix: x', "fix: y\n\nCo-authored-by: Some Tool <noreply@tool.example>"]));

