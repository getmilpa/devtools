    /**
     * Runs the gate in this process against a recorded API.
     *
     * @param array<string, string>          $env
     * @param callable(string): array<mixed> $api
     * @param list<string>                   $asked     every path that was asked, in order
     * @param list<string>                   $arguments
     *
     * @return array{int, string} the exit code and everything that was said
     */
    private function gate(array $env, callable $api, array &$asked = [], array $arguments = [], string $stdin = ''): array
    {
        $said = [];
        $fetch = static function (string $path) use ($api, &$asked): array {
            $asked[] = $path;

            return $api($path);
        };

        $code = MessageGate::run(['message-gate.php', ...$arguments], $env, $fetch, static function (string $line) use (&$said): void {
            $said[] = $line;
        }, $stdin);

        return [$code, implode("\n", $said)];
    }

    /**
     * A recorded API holding one pull request: its title, its body, and one commit per message.
     *
     * @param list<string> $messages
     *
     * @return callable(string): array<mixed>
     */
    private static function api(int $number, string $title, string $body, array $messages, string $repository = 'x/y'): callable
    {
        return static function (string $path) use ($number, $title, $body, $messages, $repository): array {
            if ($path === "/repos/{$repository}/pulls/{$number}") {
                return ['title' => $title, 'body' => $body === '' ? null : $body, 'commits' => \count($messages)];
            }

            if (preg_match("~^/repos/{$repository}/pulls/{$number}/commits\\?per_page=100&page=(\\d+)$~", $path, $m) === 1) {
                return self::page($messages, (int) $m[1]);
            }

            throw new \RuntimeException('the API answered 404 to ' . $path . '.');
        };
    }

    /**
     * A recorded API holding one comparison between two commits.
     *
     * @param list<string> $messages
     *
     * @return callable(string): array<mixed>
     */
    private static function compare(array $messages): callable
    {
        return static function (string $path) use ($messages): array {
            if (preg_match('~^/repos/x/y/compare/[0-9a-f]{40}\.\.\.[0-9a-f]{40}\?per_page=100&page=(\d+)$~', $path, $m) !== 1) {
                throw new \RuntimeException('the API answered 404 to ' . $path . '.');
            }

            return ['total_commits' => \count($messages), 'commits' => self::page($messages, (int) $m[1])];
        };
    }

    /**
     * @param list<string> $messages
     *
     * @return list<array{sha: string, commit: array{message: string}}>
     */
    private static function page(array $messages, int $page): array
    {
        $commits = [];
        foreach (\array_slice($messages, ($page - 1) * 100, 100, true) as $index => $message) {
            $commits[] = ['sha' => self::sha($index), 'commit' => ['message' => $message]];
        }

        return $commits;
    }

    private static function sha(int $index): string
    {
        return sha1('commit ' . $index);
    }

    /**
     * @return array<string, string>
     */
    private function pullRequestEvent(int $number, string $rememberedBody = 'A body.'): array
    {
        return [
            'GITHUB_EVENT_NAME' => 'pull_request',
            'GITHUB_REPOSITORY' => 'x/y',
            'GITHUB_EVENT_PATH' => $this->payload(['action' => 'opened', 'number' => $number, 'pull_request' => ['number' => $number, 'title' => 'fix: x', 'body' => $rememberedBody]]),
        ];
    }

    /**
     * @return array<string, string>
     */
    private function pushEvent(string $before, string $after): array
    {
        return [
            'GITHUB_EVENT_NAME' => 'push',
            'GITHUB_REPOSITORY' => 'x/y',
            'GITHUB_EVENT_PATH' => $this->payload(['ref' => 'refs/heads/main', 'before' => $before, 'after' => $after]),
        ];
    }

    /**
     * @param array<string, mixed> $event
     */
    private function payload(array $event): string
    {
        $file = $this->temporary[] = (string) tempnam(sys_get_temp_dir(), 'message-gate-event-');
        file_put_contents($file, json_encode($event, \JSON_THROW_ON_ERROR));

        return $file;
    }

    /**
     * Starts a local server that answers the given paths, and returns its address.
     *
     * @param array<string, array{int, array<mixed>}> $routes path (with its query) to status and answer
     */
    private function serve(array $routes): string
    {
        $routesFile = $this->temporary[] = (string) tempnam(sys_get_temp_dir(), 'message-gate-routes-');
        $logFile = $this->temporary[] = $routesFile . '.log';
        file_put_contents($routesFile, json_encode($routes, \JSON_THROW_ON_ERROR));
        file_put_contents($logFile, '');

        $probe = stream_socket_server('tcp://127.0.0.1:0');
        self::assertIsResource($probe);
        $port = (int) substr((string) strrchr((string) stream_socket_get_name($probe, false), ':'), 1);
        fclose($probe);

        $server = proc_open(
            [\PHP_BINARY, '-S', "127.0.0.1:{$port}", \dirname(__DIR__) . '/Fixtures/message-gate-api.php'],
            [['file', '/dev/null', 'r'], ['file', '/dev/null', 'w'], ['file', '/dev/null', 'w']],
            $pipes,
            null,
            ['MESSAGE_GATE_ROUTES' => $routesFile, 'MESSAGE_GATE_LOG' => $logFile],
        );
        self::assertIsResource($server);
        $this->server = $server;

        for ($waited = 0; $waited < 100; ++$waited) {
            $connection = @fsockopen('127.0.0.1', $port, $errno, $error, 0.1);
            if (\is_resource($connection)) {
                fclose($connection);

                return "http://127.0.0.1:{$port}";
            }
            usleep(50_000);
        }

        self::fail('the local server did not start');
    }

    /**
     * Every request the local server received: "<authorization> <path>".
     *
     * @return list<string>
     */
    private function requests(): array
    {
        foreach ($this->temporary as $file) {
            if (str_ends_with($file, '.log')) {
                return array_values(array_filter(explode("\n", (string) file_get_contents($file))));
            }
        }

        return [];
    }

    /**
     * Starts the script as CI does and returns its exit code and output.
     *
     * @param array<string, string> $env
     * @param list<string>          $arguments
     *
     * @return array{int, string}
     */
    private function script(array $env, array $arguments = [], string $stdin = ''): array
    {
        $process = proc_open(
            [\PHP_BINARY, \dirname(__DIR__, 2) . '/tools/message-gate.php', ...$arguments],
            [['pipe', 'r'], ['pipe', 'w'], ['pipe', 'w']],
            $pipes,
            null,
            $env,
        );
        self::assertIsResource($process);

        fwrite($pipes[0], $stdin);
        fclose($pipes[0]);
        $said = stream_get_contents($pipes[1]) . stream_get_contents($pipes[2]);
        fclose($pipes[1]);
        fclose($pipes[2]);

        return [proc_close($process), (string) $said];
    }
