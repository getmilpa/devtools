/**
 * The controls of the message gate: every refusal it promises, and every text it must let through.
 *
 * A gate with no control is not a gate. Each rule is shown red on a text that breaks it and green on
 * the nearest text that does not — the release bot's own pull request, the merge commit GitHub writes
 * when a branch is updated, the house's everyday words ("session", "generated") used as words.
 *
 * The run is driven with a recorded API so no test needs the network; the last tests start the script
 * as a process against a local server, because the request itself (token, pages, a refusal, a server
 * that fails) is where "could not read" has to end red.
 */
