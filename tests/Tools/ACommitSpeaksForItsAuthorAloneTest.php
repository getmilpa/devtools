    #[DataProvider('textsThatAreRefused')]
    public function testARefusedTextNamesItsLineAndItsRule(string $text, string $rule, int $line): void
    {
        self::assertSame([['line' => $line, 'rule' => $rule]], MessageGate::judge($text));
    }

    public function testOneLineCanBreakTwoRules(): void
    {
        $found = MessageGate::judge("fix: x\n\nTool-Session: https://tool.example/code/session_01Y1KzQQVduS83c6ZArZZ96s\nCo-authored-by: Some Tool <noreply@tool.example>");

        self::assertSame([
            ['line' => 3, 'rule' => MessageGate::SESSION],
            ['line' => 4, 'rule' => MessageGate::COAUTHOR],
        ], $found);
    }

    /** A title becomes the first line of the squashed commit; what follows "fix: " is read as that line. */
    public function testATitleIsJudgedAfterItsConventionalPrefix(): void
    {
        self::assertSame([['line' => 1, 'rule' => MessageGate::GENERATOR]], MessageGate::judge('fix(docs)!: Generated by Some Tool', true));
        self::assertSame([], MessageGate::judge('fix: Generated by Some Tool'), 'read as a commit line, the prefix opens it');
        self::assertSame([], MessageGate::judge('fix: the docs are generated by the build', true));
        self::assertSame([], MessageGate::judge('chore(main): release 1.2.3', true));
    }

