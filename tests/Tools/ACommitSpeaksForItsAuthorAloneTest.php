    // ── a push ───────────────────────────────────────────────────────────────────────────────────

    public function testAPushIsJudgedByTheCommitsItAdded(): void
    {
        $asked = [];
        $clean = self::compare(['fix: x (#7)', "chore(main): release 1.2.3 (#12)\n\nCo-authored-by: github-actions[bot] <41898282+github-actions[bot]@users.noreply.github.com>"]);
        $dirty = self::compare(['fix: x (#7)', "fix: y (#8)\n\nCo-authored-by: Some Tool <noreply@tool.example>"]);

        [$passes, $said] = $this->gate($this->pushEvent(self::sha(8), self::sha(9)), $clean, $asked);
        [$fails, $refusal] = $this->gate($this->pushEvent(self::sha(8), self::sha(9)), $dirty);

        self::assertSame(0, $passes, $said);
        self::assertStringContainsString('2 commits read', $said);
        self::assertSame(['/repos/x/y/compare/' . self::sha(8) . '...' . self::sha(9) . '?per_page=100&page=1'], $asked);
        self::assertSame(1, $fails);
        self::assertStringContainsString('commit ' . substr(self::sha(1), 0, 9) . ', line 3: ' . MessageGate::COAUTHOR, $refusal);
    }

