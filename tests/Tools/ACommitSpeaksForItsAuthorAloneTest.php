    /**
     * The body is asked of the API, never taken from the event that started the run: the event of a
     * re-run still carries the body the pull request had when it was opened.
     */
    public function testTheBodyIsReadAsItIsNowNotAsTheEventRemembersIt(): void
    {
        $stale = "Old body.\n\nGenerated with [Some Tool](https://tool.example)";

        [$cleaned] = $this->gate($this->pullRequestEvent(7, $stale), self::api(7, 'fix: x', 'Old body.', ['fix: x']));
        [$dirtied] = $this->gate($this->pullRequestEvent(7, 'Old body.'), self::api(7, 'fix: x', $stale, ['fix: x']));

        self::assertSame(0, $cleaned, 'a re-run after the body was cleaned passes');
        self::assertSame(1, $dirtied, 'a re-run after the body was dirtied does not');
    }

